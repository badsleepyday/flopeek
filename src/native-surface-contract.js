function mcpSurfaceCategory(name) {
  if (MCP_HANDLE_SAFE.has(name)) return HANDLE_SAFE;
  if (MCP_BOUNDED.has(name)) return BOUNDED;
  if (MCP_MATERIALIZED.has(name)) return MATERIALIZED;
  return null;
}

function serverSurfaceCategory(method, pathname) {
  const key = `${method} ${pathname}`;
  if (SERVER_HANDLE_SAFE.has(key)) return HANDLE_SAFE;
  if (SERVER_MATERIALIZED.has(key)) return MATERIALIZED;
  return null;
}

